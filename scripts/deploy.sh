#!/usr/bin/env bash
# Deploy ORBIT to Kubernetes with Helm.
#
# Usage:
#   KUBE_CONTEXT=microk8s ./scripts/deploy.sh
#       Local/dev profile: values.yaml plus development overrides.
#   KUBE_CONTEXT=prod VALUES=values-prod.yaml ./scripts/deploy.sh
#       Deploy the values file as written; no development overrides.
#       Passing the chart's values.yaml explicitly still selects the dev profile.
#   TAG=<version> ./scripts/deploy.sh --set ingress.host=orbit.example.com
set -euo pipefail

NAMESPACE="${NAMESPACE:-orbit}"
KUBE_CONTEXT="${KUBE_CONTEXT:-microk8s}"
RELEASE="${RELEASE:-orbit}"
# Empty VALUES (or the chart's own values.yaml, which `make deploy` passes) selects the
# throwaway local/dev profile. With an operator values file its settings win.
VALUES="${VALUES:-}"
DEFAULT_VALUES="deploy/helm/orbit/values.yaml"
VALUES_PATH="${VALUES:-$DEFAULT_VALUES}"
REGISTRY="${REGISTRY:-}"
INGRESS_HOST="${INGRESS_HOST:-}"

cd "$(dirname "$0")/.."

# Published images are tagged with the chart appVersion, so that is the real default.
DEFAULT_TAG=$(awk '/^appVersion:/ {gsub(/[",]/, "", $2); print $2; exit}' deploy/helm/orbit/Chart.yaml)
if [[ -z "$DEFAULT_TAG" ]]; then
  echo "ERROR: cannot read appVersion from deploy/helm/orbit/Chart.yaml." >&2
  exit 1
fi
TAG="${TAG:-$DEFAULT_TAG}"

echo "==> Checking cluster access (${KUBE_CONTEXT})"
if ! kubectl --context "${KUBE_CONTEXT}" get nodes >/dev/null 2>&1; then
  echo "ERROR: cannot reach cluster '${KUBE_CONTEXT}'." >&2
  echo "       Check VPN/LAN access, then retry. No resources were changed." >&2
  exit 1
fi

echo "==> Applying secret prerequisites (namespace ${NAMESPACE})"
kubectl --context "${KUBE_CONTEXT}" create namespace "${NAMESPACE}" \
  --dry-run=client -o yaml | kubectl --context "${KUBE_CONTEXT}" apply -f -

# Workers are launched from worker profiles through the launcher by default; the
# launcher token is generated by the chart and reused from the release Secret.
# The variables below only supply optional fixed workers when the values enable them.
WORKER_TOKEN=""
OP_TOKEN=""
PI_TOKEN=""
LAUNCHER_TOKEN=""
if kubectl --context "${KUBE_CONTEXT}" -n "${NAMESPACE}" get secret orbit-secrets >/dev/null 2>&1; then
  WORKER_TOKEN=$(kubectl --context "${KUBE_CONTEXT}" -n "${NAMESPACE}" get secret orbit-secrets -o jsonpath='{.data.worker-token}' 2>/dev/null | base64 -d 2>/dev/null || true)
  OP_TOKEN=$(kubectl --context "${KUBE_CONTEXT}" -n "${NAMESPACE}" get secret orbit-secrets -o jsonpath='{.data.opencode-worker-token}' 2>/dev/null | base64 -d 2>/dev/null || true)
  PI_TOKEN=$(kubectl --context "${KUBE_CONTEXT}" -n "${NAMESPACE}" get secret orbit-secrets -o jsonpath='{.data.pi-worker-token}' 2>/dev/null | base64 -d 2>/dev/null || true)
  LAUNCHER_TOKEN=$(kubectl --context "${KUBE_CONTEXT}" -n "${NAMESPACE}" get secret orbit-secrets -o jsonpath='{.data.launcher-token}' 2>/dev/null | base64 -d 2>/dev/null || true)
fi

DEV_PROFILE=0
if [[ -z "${VALUES}" || "${VALUES#./}" == "${DEFAULT_VALUES}" ]]; then
  DEV_PROFILE=1
fi

HELM_ARGS=(
  --namespace "${NAMESPACE}"
  -f "${VALUES_PATH}"
  --set api.tag="${TAG}"
  --set worker.tag="${TAG}"
  --set web.tag="${TAG}"
  --set launcher.tag="${TAG}"
  --set opencodeWorker.tag="${TAG}"
  --set piWorker.tag="${TAG}"
)

if (( DEV_PROFILE )); then
  # Throwaway local cluster only: dev auth behind the ingress and hostpath storage.
  # Never apply these on top of an operator-provided values file.
  REGISTRY="${REGISTRY:-192.168.1.201:5000}"
  INGRESS_HOST="${INGRESS_HOST:-orbit.mdk.local}"
  HELM_ARGS+=(
    --set platform.environment=development
    --set auth.acknowledgeInsecureDev=true
    --set postgresql.storageClassName=hostpath
    --set nats.storageClassName=hostpath
  )
fi

if [[ -n "${REGISTRY}" ]]; then
  HELM_ARGS+=(--set imageRegistry="${REGISTRY}")
fi

if [[ -n "${INGRESS_HOST}" ]]; then
  HELM_ARGS+=(
    --set ingress.host="${INGRESS_HOST}"
    --set platform.corsOrigins="http://${INGRESS_HOST}"
    --set platform.publicBaseUrl="http://${INGRESS_HOST}"
  )
fi

# Reuse scoped tokens from an existing release Secret. Passing a token does not enable a
# worker: worker.enabled / opencodeWorker.enabled / piWorker.enabled stay as in the values.
if [[ -n "${WORKER_TOKEN}" ]]; then HELM_ARGS+=(--set worker.token="${WORKER_TOKEN}"); fi
if [[ -n "${OP_TOKEN}" ]]; then HELM_ARGS+=(--set opencodeWorker.token="${OP_TOKEN}"); fi
if [[ -n "${PI_TOKEN}" ]]; then HELM_ARGS+=(--set piWorker.token="${PI_TOKEN}"); fi
if [[ -n "${LAUNCHER_TOKEN}" ]]; then HELM_ARGS+=(--set launcher.token="${LAUNCHER_TOKEN}"); fi

helm --kube-context "${KUBE_CONTEXT}" upgrade --install "${RELEASE}" deploy/helm/orbit \
  "${HELM_ARGS[@]}" \
  "$@"

echo
kubectl --context "${KUBE_CONTEXT}" -n "${NAMESPACE}" get pods,svc,ingress
echo
if [[ -n "${INGRESS_HOST}" ]]; then
  echo "Ingress: http://${INGRESS_HOST}/  (configure DNS/hosts to the ingress address)"
else
  echo "Ingress: see ingress.host in the values / kubectl output above"
fi
