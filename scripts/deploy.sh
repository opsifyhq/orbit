#!/usr/bin/env bash
# Deploy ORBIT to Kubernetes with Helm.
#
# Usage:
#   KUBE_CONTEXT=microk8s NAMESPACE=orbit VALUES=deploy/helm/orbit/values.yaml ./scripts/deploy.sh
#   TAG=0.1.0 ./scripts/deploy.sh --set ingress.host=orbit.mdk.local
set -euo pipefail

NAMESPACE="${NAMESPACE:-orbit}"
KUBE_CONTEXT="${KUBE_CONTEXT:-microk8s}"
RELEASE="${RELEASE:-orbit}"
VALUES="${VALUES:-deploy/helm/orbit/values.yaml}"
REGISTRY="${REGISTRY:-192.168.1.201:5000}"
TAG="${TAG:-0.1.0}"
INGRESS_HOST="${INGRESS_HOST:-orbit.mdk.local}"

cd "$(dirname "$0")/.."

echo "==> Checking cluster access (${KUBE_CONTEXT})"
if ! kubectl --context "${KUBE_CONTEXT}" get nodes >/dev/null 2>&1; then
  echo "ERROR: cannot reach cluster '${KUBE_CONTEXT}'." >&2
  echo "       Check VPN/LAN access, then retry. No resources were changed." >&2
  exit 1
fi

echo "==> Applying secret prerequisites (namespace ${NAMESPACE})"
kubectl --context "${KUBE_CONTEXT}" create namespace "${NAMESPACE}" \
  --dry-run=client -o yaml | kubectl --context "${KUBE_CONTEXT}" apply -f -

# Workers are launched from worker profiles through the launcher by default; the
# launcher token is generated by the chart and reused from the release Secret.
# The variables below only matter for the optional fixed workers.
WORKER_TOKEN=""
OP_TOKEN=""
LAUNCHER_TOKEN=""
if kubectl --context "${KUBE_CONTEXT}" -n "${NAMESPACE}" get secret orbit-secrets >/dev/null 2>&1; then
  WORKER_TOKEN=$(kubectl --context "${KUBE_CONTEXT}" -n "${NAMESPACE}" get secret orbit-secrets -o jsonpath='{.data.worker-token}' 2>/dev/null | base64 -d 2>/dev/null || true)
  OP_TOKEN=$(kubectl --context "${KUBE_CONTEXT}" -n "${NAMESPACE}" get secret orbit-secrets -o jsonpath='{.data.opencode-worker-token}' 2>/dev/null | base64 -d 2>/dev/null || true)
  LAUNCHER_TOKEN=$(kubectl --context "${KUBE_CONTEXT}" -n "${NAMESPACE}" get secret orbit-secrets -o jsonpath='{.data.launcher-token}' 2>/dev/null | base64 -d 2>/dev/null || true)
fi

# Local microk8s only: dev auth behind the ingress is acknowledged explicitly
# (auth.acknowledgeInsecureDev, see the chart guard in templates/_helpers.tpl).
helm --kube-context "${KUBE_CONTEXT}" upgrade --install "${RELEASE}" deploy/helm/orbit \
  --namespace "${NAMESPACE}" \
  -f "${VALUES}" \
  --set imageRegistry="${REGISTRY}" \
  --set api.tag="${TAG}" \
  --set worker.tag="${TAG}" \
  --set web.tag="${TAG}" \
  --set launcher.tag="${TAG}" \
  --set opencodeWorker.tag="${TAG}" \
  --set ingress.host="${INGRESS_HOST}" \
  --set platform.corsOrigins="http://${INGRESS_HOST}" \
  --set platform.publicBaseUrl="http://${INGRESS_HOST}" \
  --set platform.environment=development \
  --set auth.acknowledgeInsecureDev=true \
  --set postgresql.storageClassName=hostpath \
  --set nats.storageClassName=hostpath \
  ${WORKER_TOKEN:+--set worker.enabled=true --set worker.token="${WORKER_TOKEN}"} \
  ${OP_TOKEN:+--set opencodeWorker.token="${OP_TOKEN}"} \
  ${OP_TOKEN:+--set opencodeWorker.enabled=true} \
  ${LAUNCHER_TOKEN:+--set launcher.token="${LAUNCHER_TOKEN}"} \
  "$@"

echo
kubectl --context "${KUBE_CONTEXT}" -n "${NAMESPACE}" get pods,svc,ingress
echo
echo "Ingress: http://${INGRESS_HOST}/  (configure DNS/hosts to the ingress address)"
